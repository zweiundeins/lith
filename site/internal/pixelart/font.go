// Word spells s in colour c, a pixel between glyphs. Lowercase letters
// take their capitals; runes without a glyph are left out.
func Word(s string, c string) Grid {
	var rows [][]string
	w := 0
	for _, r := range s {
		if 'a' <= r && r <= 'z' {
			r -= 'a' - 'A'
		}
		g, ok := glyphs[r]
		if !ok {
			continue
		}
		rows = append(rows, g)
		w += len(g[0]) + 1
	}
	g := NewGrid(max(0, w-1), 7)
	x := 0
	for _, glyph := range rows {
		for y, row := range glyph {
			for i, ch := range row {
				if ch == '#' {
					g.Set(x+i, y, c)
				}
			}
		}
		x += len(glyph[0]) + 1
	}
	return g
}
